#!/usr/bin/env python3
"""Generates browser/js/text-codec-data.js from the WHATWG Encoding Standard:
the label table (https://encoding.spec.whatwg.org/encodings.json) and the
single-byte indexes (https://encoding.spec.whatwg.org/index-NAME.txt).

    python3 browser/tools/gen_text_codec_data.py DIR [OUT]

DIR holds encodings.json and the index-*.txt files (download them with
`--fetch DIR` first). OUT defaults to browser/js/text-codec-data.js.
"""

import json
import os
import sys
import urllib.request

SINGLE_BYTE = {
    "IBM866": "ibm866", "ISO-8859-2": "iso-8859-2", "ISO-8859-3": "iso-8859-3",
    "ISO-8859-4": "iso-8859-4", "ISO-8859-5": "iso-8859-5", "ISO-8859-6": "iso-8859-6",
    "ISO-8859-7": "iso-8859-7", "ISO-8859-8": "iso-8859-8", "ISO-8859-8-I": "iso-8859-8",
    "ISO-8859-10": "iso-8859-10", "ISO-8859-13": "iso-8859-13", "ISO-8859-14": "iso-8859-14",
    "ISO-8859-15": "iso-8859-15", "ISO-8859-16": "iso-8859-16", "KOI8-R": "koi8-r",
    "KOI8-U": "koi8-u", "macintosh": "macintosh", "windows-874": "windows-874",
    "windows-1250": "windows-1250", "windows-1251": "windows-1251",
    "windows-1252": "windows-1252", "windows-1253": "windows-1253",
    "windows-1254": "windows-1254", "windows-1255": "windows-1255",
    "windows-1256": "windows-1256", "windows-1257": "windows-1257",
    "windows-1258": "windows-1258", "x-mac-cyrillic": "x-mac-cyrillic",
}


def read(path):
    entries = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            pointer, code = line.split("\t")[:2]
            entries[int(pointer.strip())] = int(code, 16)
    return entries


def main():
    args = sys.argv[1:]
    if args and args[0] == "--fetch":
        os.makedirs(args[1], exist_ok=True)
        files = ["encodings.json"] + [f"index-{n}.txt" for n in sorted(set(SINGLE_BYTE.values()))]
        for name in files:
            with urllib.request.urlopen(f"https://encoding.spec.whatwg.org/{name}") as r:
                with open(os.path.join(args[1], name), "wb") as f:
                    f.write(r.read())
        return
    if not args:
        sys.exit(__doc__)
    src = args[0]
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    dst = args[1] if len(args) > 1 else os.path.join(root, "browser", "js", "text-codec-data.js")
    groups = json.load(open(os.path.join(src, "encodings.json"), encoding="utf-8"))
    labels = {label: e["name"] for g in groups for e in g["encodings"] for label in e["labels"]}
    out = ["// Generated by browser/tools/gen_text_codec_data.py from\n",
           "// https://encoding.spec.whatwg.org/ (encodings.json, index-*.txt); do not edit.\n",
           "// License: browser/licenses/WHATWG-ENCODING.\n",
           "({\n",
           "ENCODING_LABELS: " + json.dumps(labels, indent=1) + ",\n",
           "SINGLE_BYTE_INDEXES: {\n"]
    for name, index in sorted(SINGLE_BYTE.items()):
        entries = read(os.path.join(src, f"index-{index}.txt"))
        row = "".join(f"{entries.get(p, 0):04X}" for p in range(128))
        out.append(f"  {json.dumps(name)}: \"{row}\",\n")
    out.append("}\n})\n")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
