#!/usr/bin/env python3
"""Generates browser/net/hsts-preload.txt, the HSTS preload list that
net/hsts-preload.aye embeds, from Chromium's list
(net/http/transport_security_state_static.json in a Chromium checkout,
or https://chromium.googlesource.com/chromium/src/+/main/net/http/transport_security_state_static.json?format=TEXT
decoded from base64).

    python3 -I browser/tools/gen_hsts_preload.py transport_security_state_static.json [OUT]

Chromium's list has about 93,000 force-https entries (10 MB), too many
to embed. Kept: the hand-reviewed ones (policies public-suffix, google,
custom: TLDs such as .dev and .app, Google, Facebook, Twitter, PayPal...)
and the bulk entries of TOP, popular sites that preloaded through
hstspreload.org. One entry per line: the host, then " *" when it covers
its subdomains; lines starting with # are the header.
"""

import json
import os
import re
import sys

KEPT_POLICIES = {"public-suffix", "google", "custom"}
TOP = {"github.com", "wikipedia.org", "reddit.com", "instagram.com", "whatsapp.com", "icloud.com", "cloudflare.com"}


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "net", "hsts-preload.txt")
    with open(src, encoding="utf-8") as f:
        data = json.loads(re.sub(r"^\s*//.*$", "", f.read(), flags=re.M))
    lines = []
    for e in data["entries"]:
        if e.get("mode") != "force-https":
            continue
        if e["policy"] not in KEPT_POLICIES and e["name"] not in TOP:
            continue
        lines.append(e["name"] + (" *" if e.get("include_subdomains") else ""))
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Generated by browser/tools/gen_hsts_preload.py from Chromium's\n")
        f.write("# net/http/transport_security_state_static.json (BSD-style license).\n")
        f.write("".join(line + "\n" for line in sorted(set(lines))))
    print(f"{len(lines)} entries to {out}")


if __name__ == "__main__":
    main()
